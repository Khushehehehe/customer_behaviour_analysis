--Q5. Do subscribed customers spend more?
--Compare average Spend and total revenue between subscribers and non-subscribers.
select subscription_status, 
count(customer_id) as total_customers,
Round(Avg(purchase_amount_usd),2) as Average_spend, 
Round(sum(purchase_amount_usd),2) as Total_revenue
from customer
group by subscription_status 

--Q6. Which 5 products have the highest % of purchases with discounts applied ?
select item_purchased,
Round(Sum(CASE when discount_applied = 'Yes' THEN 1 else 0 END)*100.0 /Count(*),2) as Discount_rate
from customer
group by item_purchased
order by discount_rate desc limit 5;

--Q7. Segment customers into New, Returning, And Loyal based on their total
--number of previous purchases, and show the count of each segment.
Select 
CASE 
WHEN previous_purchases<=1 Then 'New' 
WHEN previous_purchases between 2 and 5 THEN 'Returning'
else 'Loyal' END as Customer_behavior,
count(*) as Customer_count 
from customer
group by Customer_behavior
order by customer_count DESC;

--Q8. What are top 3 most purchased products within each category?
WITH product_counts AS (
    SELECT
        category,
        item_purchased,
        COUNT(*) AS purchase_count
    FROM customer
    GROUP BY category, item_purchased
),
ranked_products AS (
    SELECT
        category,
        item_purchased,
        purchase_count,
        ROW_NUMBER() OVER (
            PARTITION BY category
            ORDER BY purchase_count DESC
        ) AS product_rank
    FROM product_counts
)
SELECT
    category,
    item_purchased,
    purchase_count
FROM ranked_products
WHERE product_rank <= 3
ORDER BY category, product_rank;

